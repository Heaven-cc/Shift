    const SizedBox(height: 20), const Heading('Your ideas.\nAlways in motion.', 'Your AI social media manager.'),
    const Panel(glass: true, child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
      ListTile(contentPadding: EdgeInsets.zero, leading: Icon(Icons.travel_explore), title: Text('Find your next angle'), subtitle: Text('Research that informs your content.')),
      ListTile(contentPadding: EdgeInsets.zero, leading: Icon(Icons.auto_awesome_outlined), title: Text('Create with intention'), subtitle: Text('Your voice, across every post.')),
