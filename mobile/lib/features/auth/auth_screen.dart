class AuthScreen extends StatefulWidget {
  const AuthScreen({super.key, required this.mode});
  final String mode;
  @override State<AuthScreen> createState() => _AuthScreenState();
}
class _AuthScreenState extends State<AuthScreen> {
  final key = GlobalKey<FormState>();
  final email = TextEditingController(), password = TextEditingController(), name = TextEditingController();
  bool hidden = true, busy = false;
  late String mode = widget.mode;
  @override void dispose() { email.dispose(); password.dispose(); name.dispose(); super.dispose(); }
  @override Widget build(BuildContext context) {
    final register = mode == 'register', reset = mode == 'reset', verify = mode == 'verify';
    final title = reset ? 'Reset password' : verify ? 'Verify your email' : register ? 'Register' : 'Welcome back';
    return Scaffold(appBar: AppBar(title: const Text('SHIFT')), body: PageBody(children: [
      Heading(title, verify ? 'Email verification will be handled by SHIFT authentication.' : 'Your content deserves a space of its own.'),
      const ServiceNotice(text: 'Authentication is not connected. These forms do not create accounts or transmit credentials.'),
      Form(key: key, child: Column(crossAxisAlignment: CrossAxisAlignment.stretch, children: [
        if (register) Field('Display name', controller: name, required: true),
        TextFormField(controller: email, keyboardType: TextInputType.emailAddress, autofillHints: const [AutofillHints.email], decoration: const InputDecoration(labelText: 'Email'), validator: (v) => RegExp(r'^[^@\s]+@[^@\s]+\.[^@\s]+$').hasMatch(v ?? '') ? null : 'Enter a valid email'),
        const SizedBox(height: 16),
        if (!reset && !verify) TextFormField(controller: password, obscureText: hidden, autofillHints: [register ? AutofillHints.newPassword : AutofillHints.password], decoration: InputDecoration(labelText: 'Password', suffixIcon: IconButton(tooltip: hidden ? 'Show password' : 'Hide password', onPressed: () => setState(() => hidden = !hidden), icon: Icon(hidden ? Icons.visibility_outlined : Icons.visibility_off_outlined))), validator: (v) => (v?.length ?? 0) < 8 ? 'Use at least 8 characters' : null),
        const SizedBox(height: 20),
        FilledButton(onPressed: busy ? null : () async {
          if (!key.currentState!.validate()) return;
          setState(() => busy = true);
          await unavailable(context, reset ? 'Password reset' : verify ? 'Email verification' : register ? 'Registration' : 'Sign in');
          if (mounted) setState(() => busy = false);
        }, child: Text(reset ? 'Send reset link' : verify ? 'Resend verification email' : register ? 'Register' : 'Sign In')),
        const SizedBox(height: 12),
        if (!reset && !verify) OutlinedButton.icon(onPressed: () => unavailable(context, 'Google sign in'), icon: const Icon(Icons.account_circle_outlined), label: const Text('Continue with Google')),
        TextButton(onPressed: () => setState(() => mode = reset || verify || register ? 'signin' : 'reset'), child: Text(reset || verify || register ? 'Back to Sign In' : 'Forgot password?')),
        if (!reset && !verify) TextButton(onPressed: () => setState(() => mode = register ? 'signin' : 'register'), child: Text(register ? 'Already have an account? Sign In' : 'New to SHIFT? Register')),
        TextButton(onPressed: () => setState(() => mode = 'verify'), child: const Text('Email verification help')),
        if (verify) const Panel(child: Text('Expired or invalid link? Request a new verification link when authentication is available. No verification email has been sent from this frontend.')),
      ])),
    ]));
  }
}
